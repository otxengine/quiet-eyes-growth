#!/usr/bin/env node
/**
 * Self-hosts the critical Heebo font: downloads the woff2 files (hebrew+latin
 * subsets, weights 400/500/700/800) from Google Fonts and generates
 * src/marketing/styles/fonts.css with local @font-face rules.
 *
 * Heebo drives the LCP (Hebrew headings/body) — self-hosting + preload removes
 * the late font repaint. Inter/Noto stay on the async Google link (non-critical).
 *
 * Run once (results are committed): node scripts/self-host-fonts.mjs
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FONTS_DIR = join(ROOT, 'public', 'fonts');
mkdirSync(FONTS_DIR, { recursive: true });

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Heebo:wght@400;500;700;800&display=swap';
// A woff2-capable UA makes Google return woff2 + unicode-range blocks
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();

// Parse blocks: comment names the subset, then @font-face { ... }
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]+)}/g)];
const WANTED_SUBSETS = new Set(['hebrew', 'latin']);
const rules = [];

for (const [, subset, body] of blocks) {
  if (!WANTED_SUBSETS.has(subset)) continue;
  const weight = body.match(/font-weight:\s*(\d+)/)[1];
  const url = body.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const unicodeRange = body.match(/unicode-range:\s*([^;]+);/)[1].trim();

  const file = `heebo-${weight}-${subset}.woff2`;
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  writeFileSync(join(FONTS_DIR, file), buf);
  console.log(file, Math.round(buf.length / 1024) + 'KB');

  rules.push(`@font-face {
  font-family: 'Heebo';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url(/fonts/${file}) format('woff2');
  unicode-range: ${unicodeRange};
}`);
}

const out = `/* Self-hosted Heebo (generated by scripts/self-host-fonts.mjs — do not edit by hand) */\n${rules.join('\n')}\n`;
writeFileSync(join(ROOT, 'src', 'marketing', 'styles', 'fonts.css'), out);
console.log(`✓ ${rules.length} @font-face rules → src/marketing/styles/fonts.css`);
